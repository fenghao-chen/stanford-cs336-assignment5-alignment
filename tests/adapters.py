def run_tokenize_prompt_and_output(
    prompt_strs: list[str],
    output_strs: list[str],
    tokenizer: PreTrainedTokenizerBase,
) -> dict[str, Tensor]:
    """Tokenize the prompt and output strings, and construct a mask that is 1
    for the response tokens and 0 for other tokens (prompt or padding).

    Args:
        prompt_strs: list[str], the prompt strings.
        output_strs: list[str], the output strings.
        tokenizer: PreTrainedTokenizer, the tokenizer to use.

    Returns:
        dict[str, torch.Tensor]:
            "input_ids": torch.Tensor of shape (batch_size, max(prompt_and_output_lens) - 1):
                the tokenized prompt and output strings, with the final token sliced off.
            "labels": torch.Tensor of shape (batch_size, max(prompt_and_output_lens) - 1):
                shifted input_ids (i.e., the input_ids without the first token).
            "response_mask": torch.Tensor of shape (batch_size, max(prompt_and_output_lens) - 1):
                a mask on the response tokens in `labels`.
    """
    input_ids_list = []
    labels_list = []
    mask_list = []
    max_len = 0

    padding_token_id = tokenizer.encode('<|endoftext|>')[0] # for this model

    # Concatenate first, next find out the max len, then shift accordingly
    for prompt, output in zip(prompt_strs, output_strs):
        prompt_encoded = tokenizer.encode(prompt)
        output_encoded = tokenizer.encode(output)
        full = prompt_encoded + output_encoded
        input_ids_list.append(full)
        labels_list.append(full)
        mask_list.append([False] * len(prompt_encoded) + [True] * len(output_encoded))
        max_len = max(max_len, len(full))

    for i in range(len(input_ids_list)):
        input = input_ids_list[i]
        label = labels_list[i]
        mask = mask_list[i]

        input_ids_list[i] = (input + [padding_token_id] * (max_len - len(input)))[:-1]
        labels_list[i] = (label + [padding_token_id] * (max_len - len(label))) [1:]
        mask_list[i] = (mask + [False] * (max_len - len(mask))) [1:]

    input_ids = Tensor(input_ids_list)
    labels = Tensor(labels_list)
    response_mask = Tensor(mask_list)
    return {'input_ids': input_ids, 'labels': labels, 'response_mask': response_mask}


def run_compute_group_normalized_rewards(
    reward_fn: Callable,
    rollout_responses: list[str],
    repeated_ground_truths: list[str],
    group_size: int,
    advantage_eps: float,
    normalize_by_std: bool,
) -> tuple[torch.Tensor, torch.Tensor, dict[str, float]]:
    """
    Compute rewards for each group of rollout responses, 
    normalized by the group size.

    For more on GRPO, see:
        DeepSeekMath: https://arxiv.org/abs/2402.03300
        DeepSeek-R1: https://arxiv.org/abs/2501.12948

    Args:
        reward_fn: Callable[[str, str], dict[str, float]], 
            scores the rollout responses against the ground truths, 
            producing a dict with keys 
            "reward", "format_reward", and "answer_reward".
        rollout_responses: list[str], rollouts from the policy. 
            The length of this list is 
            `rollout_batch_size = n_prompts_per_rollout_batch * group_size`.
        repeated_ground_truths: list[str], the ground truths for the examples. 
            The length of this list is `rollout_batch_size`, 
            because the ground truth for each example is repeated `group_size` times.
        group_size: int, number of rollouts per group.
        advantage_eps: float, epsilon to avoid division by zero
            during group normalization.
        normalize_by_std: bool, whether to normalize the rewards by
            std(rewards).

    Returns:
        tuple[torch.Tensor, torch.Tensor, dict[str, float]]:
            torch.Tensor of shape (rollout_batch_size,): 
                group-normalized rewards for each rollout response.
            torch.Tensor of shape (rollout_batch_size,): 
                raw rewards for each rollout response.
            dict[str, float]: metadata for the rewards of the rollout batch.
                You may choose what you wish to log here
                (some statistics of the rewards, etc.).
    """
    # Compute raw rewards
    raw_rewards = [reward_fn(response, truth)['reward']
                   for response, truth in zip(rollout_responses, repeated_ground_truths)]

    raw_rewards = torch.tensor(raw_rewards, dtype=torch.float32)

    # Reshape into groups for easier processing
    rewards_grouped = raw_rewards.view(-1, group_size)  # Shape: (n_groups, group_size)

    # Compute group means and center each group
    group_means = rewards_grouped.mean(dim=1, keepdim=True)  # Shape: (n_groups, 1)
    normalized_rewards = rewards_grouped - group_means

    # Normalize by standard deviation if requested
    if normalize_by_std:
        group_stds = torch.std(rewards_grouped, dim=1, keepdim=True)  # Sample std
        normalized_rewards = normalized_rewards / (group_stds + advantage_eps)

    # Flatten back to original shape
    normalized_rewards = normalized_rewards.flatten()

    # Create metadata
    metadata = {
        'mean_raw_reward': float(raw_rewards.mean()),
        'std_raw_reward': float(raw_rewards.std()),
        'mean_normalized_reward': float(normalized_rewards.mean()),
        'std_normalized_reward': float(normalized_rewards.std()),
    }

    return normalized_rewards, raw_rewards, metadata

def run_compute_entropy(logits: torch.Tensor) -> torch.Tensor:
    """Get the entropy of the logits (i.e., entropy of the final dimension)."""
    # logsumexp across vocabulary
    log_Z = torch.logsumexp(logits, dim=-1) # (batch, seq)

    # softmax probabilities
    probs = torch.softmax(logits, dim=-1) # (batch, seq, vocab)

    # expected logit under probs
    expected_logit = torch.sum(probs * logits, dim=-1)

    # entropy
    entropy = log_Z - expected_logit
    return entropy


def run_get_response_log_probs(
    model: torch.nn.Module,
    input_ids: torch.Tensor,
    labels: torch.Tensor,
    return_token_entropy: bool,
) -> dict[str, torch.Tensor]:
    """Get the conditional log-probs of the response given the prompt,
        and optionally the entropy of the next token predictions.

    Args:
        model: PreTrainedModel, the model to score.
        input_ids: torch.Tensor of shape (batch_size, sequence_length):
            the tokenized prompt and output.
        labels: torch.Tensor of shape (batch_size, sequence_length):
            shifted input_ids.
        return_token_entropy: bool, whether to return the entropy of the
            next token predictions.

    Returns:
        dict[str, torch.Tensor]:
            "log_probs": torch.Tensor of shape (batch_size, sequence_length):
                the conditional log-probs of the response given the prompt.
                Note that we have not masked out the token indices corresponding
                to the prompt or padding; that is done in the train loop.
            "token_entropy": Optional[torch.Tensor] of shape (batch_size, sequence_length):
                the entropy of the next token predictions. As with the log-probs,
                we have not masked out the token indices corresponding to the prompt
                or padding; that is done in the train loop.
    """
    logits = model(input_ids).logits  # (batch, seq, vocab)

    # log-probabilities over vocab
    log_probs = torch.log_softmax(logits, dim=-1) # (batch, seq, vocab)

    # Gather log-prob of the actual next token
    token_log_probs = log_probs.gather(
        dim=-1, index=labels.unsqueeze(-1)
    ).squeeze(-1)  # (batch, seq)

    result = {"log_probs": token_log_probs}

    if return_token_entropy:
        result['token_entropy'] = run_compute_entropy(logits)

    return result

def run_compute_naive_policy_gradient_loss(
    raw_rewards_or_advantages: torch.Tensor,
    policy_log_probs: torch.Tensor,
) -> torch.Tensor:
    """Compute policy gradient loss using either raw rewards or advantages.

    Args:
        raw_rewards_or_advantages: torch.Tensor of shape (batch_size, 1): 
            the raw rewards or advantages for each rollout response.
        policy_log_probs: torch.Tensor of shape (batch_size, sequence_length): 
            the log-probs of the policy.

    Returns:
        torch.Tensor of shape (batch_size, sequence_length): 
            the policy gradient per-token loss.
    """
    return raw_rewards_or_advantages * policy_log_probs * (-1)


def run_compute_grpo_clip_loss(
    advantages: torch.Tensor,
    policy_log_probs: torch.Tensor,
    old_log_probs: torch.Tensor,
    cliprange: float,
) -> tuple[torch.Tensor, dict[str, torch.Tensor]]:
    """Compute the GRPO-Clip loss.

    Args:
        advantages: torch.Tensor of shape (batch_size, 1): 
            the advantages for each rollout response.
        policy_log_probs: torch.Tensor of shape (batch_size, sequence_length): 
            the log-probs of the policy.
        old_log_probs: torch.Tensor of shape (batch_size, sequence_length): 
            the log-probs of the old policy.
        cliprange: float, the clip range for the ratio.

    Returns:
        tuple[torch.Tensor, dict[str, torch.Tensor]]:
            torch.Tensor of shape (batch_size, sequence_length): 
                the GRPO-Clip per-token loss.
            dict[str, torch.Tensor]: metadata for the GRPO-Clip loss 
                (used to compute clip fraction).
    """
    ratio = torch.exp(policy_log_probs - old_log_probs)
    clipped_ratio = torch.clamp(ratio, 1 - cliprange, 1 + cliprange)
    return -torch.minimum(ratio * advantages, clipped_ratio * advantages), {}


def run_compute_policy_gradient_loss(
    policy_log_probs: torch.Tensor,
    loss_type: str,
    raw_rewards: torch.Tensor,
    advantages: torch.Tensor,
    old_log_probs: torch.Tensor,
    cliprange: float,
) -> tuple[torch.Tensor, dict[str, torch.Tensor]]:
    """
    Wrapper that delegates to the appropriate policy gradient loss function above.
    """
    match loss_type:
        case 'no_baseline':
            if raw_rewards is None:
                raise Exception("raw_rewards must not be None if loss_type = no_baseline")
            return run_compute_naive_policy_gradient_loss(raw_rewards, policy_log_probs), {}
        case 'reinforce_with_baseline':
            if advantages is None:
                raise Exception("advantages must not be None if loss_type = reinforce_with_baseline")
            return run_compute_naive_policy_gradient_loss(advantages, policy_log_probs), {}
        case 'grpo_clip':
            if advantages is None:
                raise Exception("advantages must not be None if loss_type = grpo_clip")
            return run_compute_grpo_clip_loss(advantages, policy_log_probs, old_log_probs, cliprange)
        case _:
            raise Exception(f"loss type {loss_type} is not supported")


